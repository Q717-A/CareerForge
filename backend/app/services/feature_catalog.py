"""求职助手"了如指掌"的单一事实来源：机器可读的功能目录。

背景：助手"问水印答没有"的根因是能力地图是一份**手写静态清单**（``assistant_system.md``），
而"加水印 / 一键脱敏 / 版本对比"这类是**前端 UI 功能**，不在后端"工具"注册表里，静态清单又
漏了它们 → 助手如实说"没有"。修法不是再补一段手写清单（下次加功能还会漏），而是把功能目录
做成**同进程、同语言的可导入常量**，能力地图改为运行时从这里渲染，并由守卫测试
（``tests/test_assistant_knowledge_audit.py``）把它与工具注册表、前端菜单/指南、**README 功能表**
三方对齐。

目录分三块：

- ``FUNCTIONAL_DOMAINS``：功能域，与前端 ``App.tsx`` 的 ``MENU_ITEMS`` label **一一对应**
  （守卫测试双向断言，菜单有而目录无、或目录有而菜单无都会变红）。
- ``FEATURES``：跨功能域的**界面功能**，每项写明"在哪个界面、怎么用"。这是"工具清单"之外
  的第二层事实——UI 功能不注册成后端工具。**``domain`` 必须写该功能的真实菜单**（它未必是
  直觉上的那个：通用简历在「我的资料」而不是「简历中心」，内推在「投递台」，面试深挖在
  「事实台账」）；``where`` 必须逐条核对过界面代码，不能凭 README 转述——README 与使用指南
  都可能**超前于实现**（``tests`` 里有对应守卫，见下）。
- ``build_capability_map()`` / ``build_write_tools_line()``：从工具注册表 ``_TOOLS`` 推导出
  工具清单与写入清单，随目录一起渲染进系统提示词。

**为什么以 README 功能表为锚**：``README.md`` 的「功能特性」表是本仓库对用户可见功能的
权威清单，``AGENTS.md`` 已要求"用户可见行为变化必须更新 README"。守卫测试因此要求
**README 的每一行都能映射到目录里的功能**（双向断言）：加了功能、写了 README 却没登记到
目录，测试直接变红。这样"助手跟不上新内容"就从"靠人记得改"变成"测试会拦住"。

**已知的"文档超前于实现"**（``where`` 里如实写明，不要对外宣称可用）：简历写作增强
（STAR/话术/润色/互译）与匹配度参考分在后端与文档里都有，但**界面当前没有入口**。
"""
